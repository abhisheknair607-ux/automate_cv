"use strict";
const test=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {spawnSync}=require("node:child_process");
const root=path.resolve(__dirname,"..");
const read=name=>fs.readFileSync(path.join(root,name),"utf8");
test("Structured career UI builds and exposes one record per job, nested STAR and numbers",()=>{
 const ui=read("profile_structured_ui.js");
 const css=read("profile_structured_ui.css");
 const parse=spawnSync("node",["--check",path.join(root,"profile_structured_ui.js")],{encoding:"utf8"});
 assert.equal(parse.status,0,parse.stderr);
 assert.match(ui,/\["experience","Work experience"/);
 assert.match(ui,/achievements/);
 assert.match(ui,/Situation/);assert.match(ui,/Metric \/ numerical result/);assert.match(ui,/metricContext/);
 assert.match(ui,/data-action="|const btn=/);
 assert.match(ui,/buttons?|btn\("add-entry"/);
 assert.match(ui,/btn\("add-ach"/);
 assert.match(ui,/Download backup for Drive/);
 assert.match(ui,/original\.open\(\)/);
 assert.match(ui,/window\.GaramaalProfile=Object\.freeze/);
 assert.match(css,/max-width:720px/);
 assert.match(css,/gsp-dark/);
 assert.match(css,/focus-visible/);
});
test("Structured Profile backend has owner isolation, revision fencing and staging-only writes",()=>{
 const svc=read("profile_structured_service.js");
 const parse=spawnSync("node",["--check",path.join(root,"profile_structured_service.js")],{encoding:"utf8"});
 assert.equal(parse.status,0,parse.stderr);
 assert.match(svc,/permit\(email,key\)/);
 assert.match(svc,/DATA_COLLECTION="garamaalCareerStructuredStagingV1"/);
 assert.match(svc,/process\.env\.GARAMAAL_PROFILE_WRITES_APPROVED!=="true"/);
 assert.match(svc,/process\.env\.APP_READ_ONLY!=="true"/);
 assert.match(svc,/process\.env\.GARAMAAL_PROFILE_DATA_SCOPE!=="staging"/);
 assert.match(svc,/previous\.revision!==expected/);
 assert.match(read("profile_service.js"),/GARAMAAL_PROFILE_STRUCTURED_EDITOR==="true"/);
 assert.match(svc,/runTransaction/);
 assert.match(svc,/tx\.create\(/);
 assert.match(svc,/\.collection\("versions"\)/);
 assert.doesNotMatch(svc,/drive\/v3\/files|SPREADSHEET_ID|update-traffic/);
});
test("Staging-only structured routes are not injected into production browser",()=>{
 const server=read("server.js"),bridge=read("bridge.js");
 assert.match(server,/structuredProfileService\.register\(app,\{authenticate\}\)/);
 assert.match(server,/GARAMAAL_PROFILE_DATA_SCOPE==="staging"/);
 assert.match(server,/\/prototype\/profile-structured\.css/);
 assert.match(server,/\/prototype\/profile-structured\.js/);
 assert.match(bridge,/"profile\/structured\/read"/);
 assert.match(bridge,/"profile\/structured\/save"/);
});
